#!/usr/bin/env python3
"""Pack the built-in web editor pages without changing their HTML."""

import argparse
import gzip
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / 'src/WebFSEditorPages.h'
target = root / 'src/WebFSEditorCompressed.h'


def render():
    pages = re.findall(r'const char (\w+)\[\] PROGMEM = R"rawliteral\((.*?)\)rawliteral";', source.read_text(), re.S)
    if [name for name, _ in pages] != ['index_html', 'logout_html', 'reboot_html']:
        raise ValueError('Expected three web editor pages')
    result = ['// Generated by tools/pack_web_editor.py from WebFSEditorPages.h.', '#pragma once', '']
    for name, html in pages:
        compressed = gzip.compress(html.encode('utf8'), mtime=0)
        # Use OS=255 consistently across Python/zlib versions.
        compressed = compressed[:9] + bytes([255]) + compressed[10:]
        result.append(f'const uint8_t {name}[] PROGMEM = {{')
        for pos in range(0, len(compressed), 16):
            result.append('  ' + ','.join(f'0x{byte:02x}' for byte in compressed[pos:pos+16]) + ',')
        result.extend(['};', ''])
    return '\n'.join(result)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    output = render()
    if parser.parse_args().check:
        if target.read_text() != output:
            raise SystemExit('Packed web editor differs. Run tools/pack_web_editor.py')
    else:
        target.write_text(output)
